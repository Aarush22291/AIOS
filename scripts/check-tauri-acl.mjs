import fs from "node:fs";
import path from "node:path";

const permissionDirectory = "apps/desktop/src-tauri/permissions/autogenerated";
const capabilityPath = "apps/desktop/src-tauri/capabilities/default.json";
const capability = JSON.parse(fs.readFileSync(capabilityPath, "utf8"));
const files = fs.readdirSync(permissionDirectory).filter((file) => file.endsWith(".toml"));
const identifiers = new Set();
const errors = [];

for (const file of files) {
  const source = fs.readFileSync(path.join(permissionDirectory, file), "utf8");
  const permissionIds = [...source.matchAll(/identifier\s*=\s*"([^"]+)"/g)].map((match) => match[1]);
  const allowedCommands = [...source.matchAll(/commands\.allow\s*=\s*\["([^"]+)"\]/g)].map((match) => match[1]);

  for (const id of permissionIds) identifiers.add(id);
  if (allowedCommands.length !== 1) {
    errors.push(`${file}: expected exactly one commands.allow entry`);
    continue;
  }

  const command = allowedCommands[0];
  const kebabCommand = command.replaceAll("_", "-");
  const expected = [`allow-${kebabCommand}`, `deny-${kebabCommand}`];
  for (const id of expected) {
    if (!permissionIds.includes(id)) {
      errors.push(`${file}: missing permission identifier "${id}" for command "${command}"`);
    }
  }
}

for (const permission of capability.permissions) {
  if (permission.startsWith("core:") || permission.startsWith("opener:")) continue;
  if (!identifiers.has(permission)) {
    errors.push(`default capability references missing permission "${permission}"`);
  }
}

if (errors.length > 0) {
  console.error("Tauri ACL validation failed:");
  for (const error of errors) console.error(` - ${error}`);
  process.exit(1);
}

console.log(`Tauri ACL validation passed: ${files.length} command permission files, ${capability.permissions.length} capability entries.`);
